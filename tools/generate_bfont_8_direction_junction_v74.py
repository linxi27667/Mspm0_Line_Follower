#!/usr/bin/env python3
"""Generate a standard-G-code B-font digit/direction/junction diagnostic."""

from __future__ import annotations

import hashlib
import json
import math
import sys
from dataclasses import dataclass
from pathlib import Path

from PIL import Image, ImageDraw


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from check_firmware_no_sbow_v31 import firmware_map_no_sbow
from check_workspace_yshift15_v28 import joint_margin
from kenjoy_gfont import load_gfont


TEST_ID = "PAPER_A4_BFONT_DIGIT8_DIRECTION_JUNCTION_GCODE_V74"
FIRMWARE_MINIMUM = "PAPER_A4_STANDARD_GCODE_JUNCTION_PLANNER_V32"
FONT_PATH = (
    ROOT / "assets" / "kenjoy_gfont" / "AA_GUO_JINGMING_b7c9ccc1.gfont"
)
FONT_SHA256 = (
    "D5D8E41EF24BF380FDAB57B4746795D691CC4E2DF878A394E4FA8C6D594C09F8"
)
GCODE_PATH = ROOT / "gcode" / f"{TEST_ID}.gcode"
MANIFEST_PATH = ROOT / "gcode" / f"{TEST_ID}.json"
PREVIEW_PATH = ROOT / "docs" / "diagnostics" / f"{TEST_ID}_PREVIEW.png"
VISIBLE_HEIGHT_MM = 14.0
TANGENT_APPROACH_MM = 5.0
FEED_MM_MIN = 300
PAPER_X_RANGE_MM = (25.0, 185.0)
PAPER_Y_RANGE_MM = (130.0, 235.0)
A4_WIDTH_MM = 210.0
A4_HEIGHT_MM = 297.0


@dataclass(frozen=True)
class Stroke:
    group: str
    direction: str
    points: tuple[tuple[float, float], ...]

    @property
    def approach(self) -> tuple[float, float]:
        first, second = self.points[:2]
        length = math.dist(first, second)
        return (
            first[0] - (second[0] - first[0]) * TANGENT_APPROACH_MM / length,
            first[1] - (second[1] - first[1]) * TANGENT_APPROACH_MM / length,
        )


def split_strokes(glyph) -> tuple[tuple[tuple[float, float], ...], ...]:
    strokes: list[list[tuple[float, float]]] = []
    for point, command in zip(glyph.points, glyph.commands):
        if command == 0:
            strokes.append([point])
        elif not strokes:
            raise AssertionError("glyph begins with draw command")
        elif math.dist(strokes[-1][-1], point) > 1.0e-12:
            strokes[-1].append(point)
    return tuple(tuple(stroke) for stroke in strokes if len(stroke) >= 2)


def place_character(
    font,
    character: str,
    center: tuple[float, float],
    reverse: bool,
    group: str,
) -> tuple[Stroke, ...]:
    glyph = font.glyphs[character]
    x_min, y_min, x_max, y_max = glyph.bounds
    scale = VISIBLE_HEIGHT_MM / (y_max - y_min)
    width = (x_max - x_min) * scale
    left = center[0] - width / 2.0
    bottom = center[1] - VISIBLE_HEIGHT_MM / 2.0
    result = []
    for source_stroke in split_strokes(glyph):
        points = tuple(
            (
                left + (point[0] - x_min) * scale,
                bottom + (point[1] - y_min) * scale,
            )
            for point in source_stroke
        )
        if reverse:
            points = tuple(reversed(points))
        result.append(
            Stroke(
                group,
                "REV" if reverse else "FWD",
                points,
            )
        )
    return tuple(result)


def analytic_stroke(
    group: str,
    points: tuple[tuple[float, float], ...],
) -> Stroke:
    return Stroke(group, "REFERENCE", points)


def build_plan(font) -> tuple[Stroke, ...]:
    result: list[Stroke] = []

    # Same source path overlaid in opposite traversal directions.  Any split
    # is generated by direction/history/mechanics, not by glyph geometry.
    for column, center_x in enumerate((45.0, 105.0, 165.0), start=1):
        result.extend(
            place_character(
                font, "8", (center_x, 220.0), False,
                f"D8_OVERLAY_C{column}",
            )
        )
        result.extend(
            place_character(
                font, "8", (center_x, 220.0), True,
                f"D8_OVERLAY_C{column}",
            )
        )

    # Original B-font digit shapes at left, exact reversed traversals at right.
    digit_centers = (36.0, 52.0, 68.0, 84.0)
    for character, center_x in zip("0689", digit_centers):
        result.extend(
            place_character(
                font, character, (center_x, 184.0), False,
                f"DIGITS_FWD_{character}",
            )
        )
    for character, center_x in zip("0689", (126.0, 142.0, 158.0, 174.0)):
        result.extend(
            place_character(
                font, character, (center_x, 184.0), True,
                f"DIGITS_REV_{character}",
            )
        )

    # Exact geometric joints.  These are independent pen strokes and do not
    # rely on any font.  The commanded meeting point is mathematically exact.
    # T: vertical ends at the midpoint of the horizontal.
    result.append(
        analytic_stroke("JOINT_T", ((39.0, 151.0), (51.0, 151.0)))
    )
    result.append(
        analytic_stroke("JOINT_T", ((45.0, 139.0), (45.0, 151.0)))
    )
    # Plus: two independent strokes cross at their exact midpoints.
    result.append(
        analytic_stroke("JOINT_PLUS", ((99.0, 145.0), (111.0, 145.0)))
    )
    result.append(
        analytic_stroke("JOINT_PLUS", ((105.0, 139.0), (105.0, 151.0)))
    )
    # X: two independent diagonals cross at the same commanded point.
    result.append(
        analytic_stroke("JOINT_X", ((159.0, 139.0), (171.0, 151.0)))
    )
    result.append(
        analytic_stroke("JOINT_X", ((159.0, 151.0), (171.0, 139.0)))
    )
    return tuple(result)


def line_samples(
    start: tuple[float, float],
    target: tuple[float, float],
    spacing: float = 1.0,
) -> tuple[tuple[float, float], ...]:
    count = max(1, math.ceil(math.dist(start, target) / spacing))
    return tuple(
        (
            start[0] + (target[0] - start[0]) * index / count,
            start[1] + (target[1] - start[1]) * index / count,
        )
        for index in range(1, count + 1)
    )


def audit(plan: tuple[Stroke, ...]) -> dict[str, object]:
    worst = (float("inf"), (0.0, 0.0))
    sample_count = 0
    for stroke in plan:
        for point in (stroke.approach, *stroke.points):
            if not (
                PAPER_X_RANGE_MM[0] <= point[0] <= PAPER_X_RANGE_MM[1]
                and PAPER_Y_RANGE_MM[0] <= point[1] <= PAPER_Y_RANGE_MM[1]
            ):
                raise AssertionError(f"V74 point out of bounds: {point}")
        previous = stroke.approach
        for target in stroke.points:
            for paper in line_samples(previous, target):
                margin, _ = joint_margin(firmware_map_no_sbow(paper))
                if margin < worst[0]:
                    worst = (margin, paper)
                sample_count += 1
            previous = target
    if worst[0] < -0.001:
        raise AssertionError(f"V74 joint limit violation: {worst}")
    return {
        "sample_count": sample_count,
        "minimum_joint_margin_deg": worst[0],
        "minimum_margin_at_paper_mm": list(worst[1]),
    }


def gcode_lines(plan: tuple[Stroke, ...]) -> tuple[str, ...]:
    lines = [
        f"; {TEST_ID}",
        f"; firmware_minimum={FIRMWARE_MINIMUM}",
        "; coordinates=STANDARD_A4_PHYSICAL_PAPER_MM",
        "; offline_mapping=NONE offline_prewarp=NONE",
        f"; font={FONT_PATH.name} sha256={FONT_SHA256}",
        "; row1=three_Bfont_8_forward_reverse_exact_overlays",
        "; row2=left_0689_forward right_0689_reverse",
        "; row3=analytic_T_PLUS_X_exact_independent_junctions",
        f"; visible_height={VISIBLE_HEIGHT_MM:.0f}mm approach={TANGENT_APPROACH_MM:.0f}mm",
        "G21",
        "G90",
        "G94",
        f"F{FEED_MM_MIN}",
        "S1000",
        "M5",
    ]
    previous_group = ""
    for index, stroke in enumerate(plan, start=1):
        if stroke.group != previous_group:
            lines.append(
                f"; GROUP={stroke.group} DIRECTION={stroke.direction}"
            )
            previous_group = stroke.group
        lines.extend(
            (
                f"; stroke={index}",
                f"G0 X{stroke.approach[0]:.3f} Y{stroke.approach[1]:.3f}",
                f"G0 X{stroke.points[0][0]:.3f} Y{stroke.points[0][1]:.3f}",
                "M3",
            )
        )
        lines.extend(
            f"G1 X{point[0]:.3f} Y{point[1]:.3f}"
            for point in stroke.points[1:]
        )
        lines.append("M5")
    lines.append("M5")
    return tuple(lines)


def preview_xy(point: tuple[float, float]) -> tuple[int, int]:
    scale = 4.0
    return (
        round(point[0] * scale),
        round((A4_HEIGHT_MM - point[1]) * scale),
    )


def write_preview(plan: tuple[Stroke, ...]) -> None:
    scale = 4.0
    image = Image.new(
        "RGB",
        (
            round(A4_WIDTH_MM * scale) + 1,
            round(A4_HEIGHT_MM * scale) + 1,
        ),
        "white",
    )
    draw = ImageDraw.Draw(image)
    draw.rectangle(
        (0, 0, image.width - 1, image.height - 1),
        outline=(20, 20, 20),
        width=3,
    )
    colors = {
        "FWD": (25, 85, 195),
        "REV": (210, 45, 35),
        "REFERENCE": (30, 30, 30),
    }
    for stroke in plan:
        draw.line(
            [preview_xy(point) for point in stroke.points],
            fill=colors[stroke.direction],
            width=3,
            joint="curve",
        )
    draw.text(
        (18, 16),
        "V74: B-font 8 FWD/REV overlay + 0689 + exact T/+ /X joints",
        fill=(20, 20, 20),
    )
    PREVIEW_PATH.parent.mkdir(parents=True, exist_ok=True)
    image.save(PREVIEW_PATH)


def main() -> None:
    actual_hash = hashlib.sha256(FONT_PATH.read_bytes()).hexdigest().upper()
    if actual_hash != FONT_SHA256:
        raise AssertionError("B-font hash changed")
    font = load_gfont(FONT_PATH)
    for character in "0689":
        if character not in font.glyphs:
            raise AssertionError(f"B font misses {character!r}")
    plan = build_plan(font)
    safety = audit(plan)
    lines = gcode_lines(plan)
    text = "\n".join(lines) + "\n"
    GCODE_PATH.parent.mkdir(parents=True, exist_ok=True)
    GCODE_PATH.write_text(text, encoding="ascii", newline="\n")
    manifest = {
        "id": TEST_ID,
        "firmware_minimum": FIRMWARE_MINIMUM,
        "purpose": [
            "separate B-font digit-8 source geometry from motion error",
            "detect direction/history-dependent splitting on the same locus",
            "measure disconnected-stroke junction error without a font",
        ],
        "font": {
            "file": FONT_PATH.name,
            "sha256": FONT_SHA256,
            "geometry": "unmodified_gfont",
            "visible_height_mm": VISIBLE_HEIGHT_MM,
        },
        "motion": {
            "feed_mm_min": FEED_MM_MIN,
            "tangent_approach_mm": TANGENT_APPROACH_MM,
            "stroke_count": len(plan),
        },
        "safety": safety,
        "gcode": {
            "file": GCODE_PATH.name,
            "line_count": len(lines),
            "sha256": hashlib.sha256(text.encode("ascii")).hexdigest().upper(),
        },
    }
    MANIFEST_PATH.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    write_preview(plan)
    print(
        f"{TEST_ID}=PASS strokes={len(plan)} "
        f"min_joint_margin={safety['minimum_joint_margin_deg']:.6f}deg "
        f"gcode_sha256={manifest['gcode']['sha256']}"
    )
    print(GCODE_PATH)
    print(MANIFEST_PATH)
    print(PREVIEW_PATH)


if __name__ == "__main__":
    main()
